const GOVERNANCE_DIGEST_B64U = 'hUXBekkP6CYYQtt4VJAzSMt0jTshXPte-Te5Q0uBKpc';
const ROOT_COMMITMENT_B64U = '6IKxMQFrUsHTM3CAGHz3aEI-_Mu1F7tJWrgSxBYP9E4';
const RECIPIENT_PAIR_DIGEST_B64U = 'mpqampqampqampqampqampqampqampqampqampqampo';
const RECOVERY_SET_ID_B64U = 'QUFBQUFBQUFBQUFBQUFBQQ';
const RESTORE_NONCE_B64U = 'UVFRUVFRUVFRUVFRUVFRUVFRUVFRUVFRUVFRUVFRUVE';
const RESTORE_MANIFEST_DIGEST_B64U = 'YWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWFhYWE';
